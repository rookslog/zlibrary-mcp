const aliases = new Map<string, string>(
  languages.flatMap(([native, ...codes]) =>
    [native, ...codes].map((value): [string, string] => [value.toLowerCase(), native]),
  ),
);

export function normalizeLanguages(values: readonly string[]): {
  values: string[];
  unrecognized: string[];
} {
  const unrecognized: string[] = [];
  return {
    values: values.flatMap((value) => {
      const key = value.normalize('NFC').trim().toLowerCase();
      if (!key) return [];
      const native = aliases.get(key);
      if (native !== undefined) return [native];
      unrecognized.push(value);
      return [value];
    }),
    unrecognized,
  };
}
